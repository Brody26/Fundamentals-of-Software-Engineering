a = int(input('Введите первое число в диапазоне от 1 до 1000:'))
b = int(input('Введите второе число в диапазоне от 1 до 1000:'))

diff = (a - b) if a < 1000 and b < 1000 else exit("Ошибка: Числа находятся в другом диапазоне!")

k = (diff // 1000) + 1
max_num = a * k + b * (1 - k)

print('Числа равны' if diff == 0 else f'Максимальное число: {max_num}')
